_BLANK = ('00000',) * 5
_HALF = {(0, 0): ' ', (1, 0): '▀', (0, 1): '▄', (1, 1): '█'}


def big_text(text: str, *, style: str = '') -> Text:
    """Render a string as 3-row half-block banner text."""
    glyphs = [_GLYPHS.get(c, _BLANK) for c in str(text).upper()]
    if not glyphs:
        return Text('', style=style)
    rows = []
    for top in range(0, 6, 2):
        cells = []
        for g in glyphs:
            up = g[top] if top < len(g) else '00000'
            lo = g[top + 1] if top + 1 < len(g) else '00000'
            cells.append(''.join(_HALF[(int(up[c]), int(lo[c]))] for c in range(5)))
        rows.append(' '.join(cells))
    return Text('\n'.join(rows), style=style)
